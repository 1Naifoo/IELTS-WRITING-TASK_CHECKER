export const TASK_ACHIEVEMENT = `Task Achievement (Task 1, Academic)
Looks at: a clear overview of the main trends or stages, sensible choice of key features, accurate data, useful comparisons, enough detail, no personal opinion or causes that are not shown.
- Band 9: every requirement met; the overview is clear and insightful; key features are chosen and illustrated skilfully; no data mistakes.
- Band 7: a clear overview; the main features are presented and highlighted, though some could be developed further; data is accurate with only minor slips.
- Band 6: an overview is present; key features are covered but some details are irrelevant, inaccurate or thin.
- Band 5: no clear overview, or the response mostly lists details mechanically; key features are not well chosen; some data may be wrong.
- Band 4 or below: the task is barely addressed; features are missing, confused or largely inaccurate.
Penalise responses under 150 words, copied question wording, and opinions or explanations not supported by the visual.`

export const TASK_RESPONSE = `Task Response (Task 2)
Looks at: whether every part of the question is answered, a clear position kept from start to finish, and main ideas that are relevant, developed and supported.
- Band 9: every part answered fully; a well-developed position; ideas are relevant, extended and well supported.
- Band 7: every part answered; a clear position throughout; main ideas are extended and supported, though some may over-generalise or lose focus.
- Band 6: every part addressed, but some more fully than others; a relevant position, though conclusions may be unclear or repetitive; some ideas lack development.
- Band 5: only part of the task is addressed; the position is not always clear; ideas are limited or not developed, possibly with irrelevant detail.
- Band 4 or below: the response is minimal or off-topic; no clear position; very few ideas.
Penalise responses under 250 words, memorised or off-topic material, and missing parts of a two-part question.`

export const COHERENCE = `Coherence and Cohesion
Looks at: logical order of ideas, clear paragraphing with one main idea each, a range of linking words used naturally, clear referencing (it, this, they), and no over-use of connectors.
- Band 9: cohesion is so natural it is barely noticed; paragraphing is skilful.
- Band 7: information is logically organised with clear progression; a range of linking devices with some over- or under-use; a clear central topic in each paragraph.
- Band 6: organisation is coherent overall; linking is effective but sometimes faulty or mechanical; referencing is not always clear; paragraphing may not always be logical.
- Band 5: some organisation but weak overall progression; linking is limited, repetitive or inaccurate; paragraphing may be missing or poor.
- Band 4 or below: ideas are not arranged coherently; basic or incorrect linking; little or no paragraphing.`

export const LEXICAL = `Lexical Resource
Looks at: range of vocabulary, precision, natural collocation, less common words used well, word formation, and spelling.
- Band 9: wide, precise, natural vocabulary; only very rare slips.
- Band 7: enough range to be flexible and precise; some less common words with awareness of style and collocation; occasional errors in word choice, spelling or word formation.
- Band 6: adequate range; attempts less common words with some inaccuracy; some spelling or word-formation errors that do not block understanding.
- Band 5: limited range, minimally adequate; noticeable errors in spelling or word formation that may make reading harder.
- Band 4 or below: basic, repetitive vocabulary; frequent errors that make meaning unclear.`

export const GRAMMAR = `Grammatical Range and Accuracy
Looks at: range of sentence structures (simple, compound, complex), accuracy, punctuation, how often errors happen and how much they affect meaning.
- Band 9: wide range used flexibly and accurately; only rare slips.
- Band 7: a variety of complex structures; frequent error-free sentences; good control with a few errors.
- Band 6: a mix of simple and complex forms; some errors in grammar and punctuation, but they rarely reduce understanding.
- Band 5: limited range; complex sentences are attempted but tend to be less accurate than simple ones; frequent errors that may cause some difficulty for the reader.
- Band 4 or below: very limited range; errors are frequent and often affect meaning; punctuation is often faulty.`

export const GENERAL_RULES = `Scoring rules:
- Give each criterion its own band from 0 to 9 in steps of 0.5. Judge each criterion against its guidance as a whole; a band is not a count of errors.
- Be realistic and slightly conservative. AI scoring tends to be generous, so do not reward length, big words or memorised phrases on their own.
- Do NOT give an overall band. The app calculates it.
- Every criterion needs at least one evidence quote copied word for word from the learner's text.`
